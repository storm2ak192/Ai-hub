    fun resolveSiteDescription(siteId: String, storedDescription: String, seedEnglishDescriptions: Set<String>): String {
        val localized = defaultSiteDescriptions[siteId]
        return if (localized != null && (storedDescription.isBlank() || storedDescription in seedEnglishDescriptions)) {
            localized
        } else {
            storedDescription
        }
    }
}

